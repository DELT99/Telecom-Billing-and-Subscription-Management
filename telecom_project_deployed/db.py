# --- Monthly Report ---
def get_monthly_report(year=None, month=None):
    """Generate a comprehensive monthly report summary"""
    from datetime import datetime
    
    if year is None:
        year = datetime.now().year
    if month is None:
        month = datetime.now().month
    
    # Initialize report with default values
    report = {
        'year': year,
        'month': month,
        'month_name': datetime(year, month, 1).strftime('%B %Y'),
        'total_active_customers': 0,
        'total_revenue': 0,
        'total_payments': 0,
        # Accounts receivable as-of-now (all unpaid/partial invoices)
        'outstanding_amount': 0,
        # Outstanding limited to invoices in the selected month
        'outstanding_amount_month': 0,
        'invoice_status_breakdown': {},
        'payment_methods': [],
        'open_complaints': 0,
        'top_customers': [],
        'new_customers': 0,
        'invoice_count_month': 0,
        'payments_count_month': 0,
        'avg_invoice_value_month': 0,
        'avg_payment_value_month': 0,
        # Collections/outstanding views that look professional in a report
        'outstanding_by_customer': [],
        'aging_buckets': {
            'current': 0,
            '1_30': 0,
            '31_60': 0,
            '61_90': 0,
            '90_plus': 0,
        },
    }
    
    try:
        # Total active customers
        try:
            conn = get_connection()
            if conn:
                cursor = conn.cursor()
                cursor.execute("SELECT COUNT(*) FROM customer WHERE account_status = 'ACTIVE'")
                row = cursor.fetchone()
                report['total_active_customers'] = row[0] if row else 0
                cursor.close()
                conn.close()
                print(f"✓ Active customers: {report['total_active_customers']}")
        except Exception as e:
            print(f"✗ Error getting active customers: {e}")
        
        # Total revenue (invoices) for the month using EXTRACT
        try:
            conn = get_connection()
            if conn:
                cursor = conn.cursor()
                cursor.execute("""
                    SELECT NVL(SUM(total_amount), 0) FROM invoice 
                    WHERE EXTRACT(YEAR FROM billing_period_start) = :1
                    AND EXTRACT(MONTH FROM billing_period_start) = :2
                """, (year, month))
                row = cursor.fetchone()
                report['total_revenue'] = float(row[0]) if row else 0
                cursor.close()
                conn.close()
                print(f"✓ Total revenue: {report['total_revenue']}")
        except Exception as e:
            print(f"✗ Error getting revenue: {e}")
        
        # Invoice count for the month
        try:
            conn = get_connection()
            if conn:
                cursor = conn.cursor()
                cursor.execute("""
                    SELECT COUNT(*) FROM invoice
                    WHERE EXTRACT(YEAR FROM billing_period_start) = :1
                    AND EXTRACT(MONTH FROM billing_period_start) = :2
                """, (year, month))
                row = cursor.fetchone()
                report['invoice_count_month'] = int(row[0]) if row else 0
                cursor.close()
                conn.close()
        except Exception as e:
            print(f"✗ Error getting invoice count: {e}")

        # Total payments received for the month
        try:
            conn = get_connection()
            if conn:
                cursor = conn.cursor()
                cursor.execute("""
                    SELECT NVL(SUM(amount_paid), 0) FROM payment 
                    WHERE EXTRACT(YEAR FROM payment_date) = :1
                    AND EXTRACT(MONTH FROM payment_date) = :2
                """, (year, month))
                row = cursor.fetchone()
                report['total_payments'] = float(row[0]) if row else 0
                cursor.close()
                conn.close()
                print(f"✓ Total payments: {report['total_payments']}")
        except Exception as e:
            print(f"✗ Error getting payments: {e}")

        # Payment count for the month
        try:
            conn = get_connection()
            if conn:
                cursor = conn.cursor()
                cursor.execute("""
                    SELECT COUNT(*) FROM payment
                    WHERE EXTRACT(YEAR FROM payment_date) = :1
                    AND EXTRACT(MONTH FROM payment_date) = :2
                """, (year, month))
                row = cursor.fetchone()
                report['payments_count_month'] = int(row[0]) if row else 0
                cursor.close()
                conn.close()
        except Exception as e:
            print(f"✗ Error getting payment count: {e}")
        
        # Outstanding amount (unpaid + partial)
        try:
            conn = get_connection()
            if conn:
                cursor = conn.cursor()
                cursor.execute("""
                    SELECT NVL(SUM(total_amount - NVL(amount_paid, 0)), 0) FROM invoice 
                    WHERE invoice_status IN ('UNPAID', 'PARTIAL')
                """)
                row = cursor.fetchone()
                report['outstanding_amount'] = float(row[0]) if row else 0
                cursor.close()
                conn.close()
                print(f"✓ Outstanding amount: {report['outstanding_amount']}")
        except Exception as e:
            print(f"✗ Error getting outstanding: {e}")

        # Outstanding amount limited to selected month invoices
        try:
            conn = get_connection()
            if conn:
                cursor = conn.cursor()
                cursor.execute("""
                    SELECT NVL(SUM(total_amount - NVL(amount_paid, 0)), 0) FROM invoice
                    WHERE invoice_status IN ('UNPAID', 'PARTIAL')
                    AND EXTRACT(YEAR FROM billing_period_start) = :1
                    AND EXTRACT(MONTH FROM billing_period_start) = :2
                """, (year, month))
                row = cursor.fetchone()
                report['outstanding_amount_month'] = float(row[0]) if row else 0
                cursor.close()
                conn.close()
        except Exception as e:
            print(f"✗ Error getting monthly outstanding: {e}")

        # Outstanding by customer (top 10) as-of-now
        try:
            conn = get_connection()
            if conn:
                cursor = conn.cursor()
                cursor.execute("""
                    SELECT
                        cu.customer_id,
                        cu.first_name || ' ' || cu.last_name AS name,
                        COUNT(i.invoice_id) AS invoice_count,
                        NVL(SUM(i.total_amount - NVL(i.amount_paid, 0)), 0) AS outstanding
                    FROM customer cu
                    JOIN invoice i ON i.customer_id = cu.customer_id
                    WHERE i.invoice_status IN ('UNPAID', 'PARTIAL')
                    GROUP BY cu.customer_id, cu.first_name, cu.last_name
                    ORDER BY outstanding DESC
                """)
                rows = cursor.fetchall()
                outstanding_by_customer = []
                for idx, row in enumerate(rows or []):
                    if not row or idx >= 10:
                        break
                    outstanding_by_customer.append({
                        'customer_id': row[0],
                        'name': row[1],
                        'invoice_count': int(row[2]) if row[2] is not None else 0,
                        'outstanding': float(row[3]) if row[3] is not None else 0,
                    })
                report['outstanding_by_customer'] = outstanding_by_customer
                cursor.close()
                conn.close()
        except Exception as e:
            print(f"✗ Error getting outstanding by customer: {e}")

        # Aging buckets for outstanding invoices as-of-now (based on due_date vs SYSDATE)
        try:
            conn = get_connection()
            if conn:
                cursor = conn.cursor()
                cursor.execute("""
                    SELECT
                        SUM(CASE WHEN TRUNC(SYSDATE) <= TRUNC(due_date)
                            THEN (total_amount - NVL(amount_paid, 0)) ELSE 0 END) AS current_amt,
                        SUM(CASE WHEN TRUNC(SYSDATE) > TRUNC(due_date) AND TRUNC(SYSDATE) - TRUNC(due_date) BETWEEN 1 AND 30
                            THEN (total_amount - NVL(amount_paid, 0)) ELSE 0 END) AS a_1_30,
                        SUM(CASE WHEN TRUNC(SYSDATE) - TRUNC(due_date) BETWEEN 31 AND 60
                            THEN (total_amount - NVL(amount_paid, 0)) ELSE 0 END) AS a_31_60,
                        SUM(CASE WHEN TRUNC(SYSDATE) - TRUNC(due_date) BETWEEN 61 AND 90
                            THEN (total_amount - NVL(amount_paid, 0)) ELSE 0 END) AS a_61_90,
                        SUM(CASE WHEN TRUNC(SYSDATE) - TRUNC(due_date) > 90
                            THEN (total_amount - NVL(amount_paid, 0)) ELSE 0 END) AS a_90_plus
                    FROM invoice
                    WHERE invoice_status IN ('UNPAID', 'PARTIAL')
                """)
                row = cursor.fetchone()
                if row:
                    report['aging_buckets'] = {
                        'current': float(row[0] or 0),
                        '1_30': float(row[1] or 0),
                        '31_60': float(row[2] or 0),
                        '61_90': float(row[3] or 0),
                        '90_plus': float(row[4] or 0),
                    }
                cursor.close()
                conn.close()
        except Exception as e:
            print(f"✗ Error getting aging buckets: {e}")
        
        # Invoice status breakdown
        try:
            conn = get_connection()
            if conn:
                cursor = conn.cursor()
                cursor.execute("""
                    SELECT invoice_status, COUNT(*) as count 
                    FROM invoice 
                    WHERE EXTRACT(YEAR FROM billing_period_start) = :1
                    AND EXTRACT(MONTH FROM billing_period_start) = :2
                    GROUP BY invoice_status
                """, (year, month))
                status_breakdown = {}
                rows = cursor.fetchall()
                for row in rows:
                    if row:
                        status_breakdown[row[0]] = row[1]
                report['invoice_status_breakdown'] = status_breakdown
                cursor.close()
                conn.close()
                print(f"✓ Invoice status breakdown: {status_breakdown}")
        except Exception as e:
            print(f"✗ Error getting invoice status breakdown: {e}")
        
        # Payment method breakdown
        try:
            conn = get_connection()
            if conn:
                cursor = conn.cursor()
                cursor.execute("""
                    SELECT payment_method, COUNT(*) as count, NVL(SUM(amount_paid), 0) as total
                    FROM payment 
                    WHERE EXTRACT(YEAR FROM payment_date) = :1
                    AND EXTRACT(MONTH FROM payment_date) = :2
                    GROUP BY payment_method
                """, (year, month))
                payment_methods = []
                rows = cursor.fetchall()
                for row in rows:
                    if row:
                        payment_methods.append({
                            'method': row[0],
                            'count': row[1],
                            'total': float(row[2]) if row[2] else 0
                        })
                report['payment_methods'] = payment_methods
                cursor.close()
                conn.close()
                print(f"✓ Payment methods: {len(payment_methods)} methods")
        except Exception as e:
            print(f"✗ Error getting payment methods: {e}")
        
        # Open complaints
        try:
            conn = get_connection()
            if conn:
                cursor = conn.cursor()
                cursor.execute("SELECT COUNT(*) FROM complaint WHERE status = 'OPEN'")
                row = cursor.fetchone()
                report['open_complaints'] = row[0] if row else 0
                cursor.close()
                conn.close()
                print(f"✓ Open complaints: {report['open_complaints']}")
        except Exception as e:
            print(f"✗ Error getting complaints: {e}")
        
        # Top 5 customers by revenue
        try:
            conn = get_connection()
            if conn:
                cursor = conn.cursor()
                cursor.execute("""
                    SELECT cu.customer_id, cu.first_name || ' ' || cu.last_name as name,
                           COUNT(i.invoice_id) as invoice_count, NVL(SUM(i.total_amount), 0) as total_revenue
                    FROM customer cu
                    LEFT JOIN invoice i ON cu.customer_id = i.customer_id 
                        AND EXTRACT(YEAR FROM i.billing_period_start) = :1
                        AND EXTRACT(MONTH FROM i.billing_period_start) = :2
                    GROUP BY cu.customer_id, cu.first_name, cu.last_name
                    ORDER BY total_revenue DESC
                """, (year, month))
                top_customers = []
                rows = cursor.fetchall()
                count = 0
                for row in rows:
                    if row and count < 5:
                        top_customers.append({
                            'customer_id': row[0],
                            'name': row[1],
                            'invoice_count': row[2],
                            'total_revenue': float(row[3]) if row[3] else 0
                        })
                        count += 1
                report['top_customers'] = top_customers
                cursor.close()
                conn.close()
                print(f"✓ Top customers: {len(top_customers)} customers")
        except Exception as e:
            print(f"✗ Error getting top customers: {e}")
        
        # New customers this month
        try:
            conn = get_connection()
            if conn:
                cursor = conn.cursor()
                cursor.execute("""
                    SELECT COUNT(*) FROM customer 
                    WHERE EXTRACT(YEAR FROM registration_date) = :1
                    AND EXTRACT(MONTH FROM registration_date) = :2
                """, (year, month))
                row = cursor.fetchone()
                report['new_customers'] = row[0] if row else 0
                cursor.close()
                conn.close()
                print(f"✓ New customers: {report['new_customers']}")
        except Exception as e:
            print(f"✗ Error getting new customers: {e}")
        
        print("✓ Monthly report generated successfully")
        # Derived metrics
        if report['invoice_count_month'] > 0:
            report['avg_invoice_value_month'] = float(report['total_revenue']) / float(report['invoice_count_month'])
        else:
            report['avg_invoice_value_month'] = 0

        if report['payments_count_month'] > 0:
            report['avg_payment_value_month'] = float(report['total_payments']) / float(report['payments_count_month'])
        else:
            report['avg_payment_value_month'] = 0

        return report
    except Exception as e:
        print(f"✗ Fatal error in get_monthly_report: {e}")
        import traceback
        traceback.print_exc()
        return report  # Return partial report with defaults
