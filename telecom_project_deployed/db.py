def subscribe_customer_to_plan(customer_id, plan_id, start_date_s=None, subscription_fee_paid=None, generate_invoice=True):
    """
    Subscribe a customer to a plan and (optionally) auto-generate an invoice for the plan rental.

    Returns: (success: bool, message: str, invoice_id: int|None)
    """
    conn = get_connection()
    if not conn:
        return False, "Database connection failed", None

    cursor = None
    try:
        cursor = conn.cursor()

        # Parse start_date (default today)
        if start_date_s:
            start_dt = datetime.strptime(start_date_s, "%Y-%m-%d").date()
        else:
            start_dt = date.today()

        # Load plan details
        cursor.execute("""
            SELECT plan_name, monthly_rental, validity_days, plan_status
            FROM subscription_plan
            WHERE plan_id = :1
        """, (plan_id,))
        plan_row = cursor.fetchone()
        if not plan_row:
            return False, "Plan not found.", None

        plan_name, monthly_rental, validity_days, plan_status = plan_row
        if plan_status != "ACTIVE":
            return False, "Selected plan is not ACTIVE.", None

        validity_days = int(validity_days) if validity_days is not None else 30
        rental = float(monthly_rental) if monthly_rental is not None else 0.0

        # Compute end_date for this subscription (inclusive)
        end_dt = start_dt + timedelta(days=max(validity_days, 1) - 1)

        # Default fee paid = rental (common for prepaid plan purchase)
        if subscription_fee_paid is None or subscription_fee_paid == "":
            fee_paid = rental
        else:
            fee_paid = float(subscription_fee_paid)

        # Insert subscription
        cursor.execute("""
            INSERT INTO customer_subscription (
                customer_id, plan_id, start_date, end_date,
                subscription_status, subscription_fee_paid
            ) VALUES (
                :1, :2, TO_DATE(:3,'YYYY-MM-DD'), TO_DATE(:4,'YYYY-MM-DD'),
                'ACTIVE', :5
            )
        """, (customer_id, plan_id, start_dt.strftime("%Y-%m-%d"), end_dt.strftime("%Y-%m-%d"), fee_paid))

        new_invoice_id = None
        if generate_invoice:
            # Ensure due_date satisfies ck_invoice_due (due_date >= generated_date)
            gen_dt = date.today()
            anchor_dt = end_dt if end_dt > gen_dt else gen_dt
            due_dt = anchor_dt + timedelta(days=10)

            # Generate invoice
            cursor.execute("SELECT NVL(MAX(invoice_id), 0) + 1 FROM invoice")
            new_invoice_id = int(cursor.fetchone()[0])

            usage = 0.0
            tax = 0.0
            total = rental + usage + tax

            cursor.execute("""
                INSERT INTO invoice (
                    invoice_id, customer_id, billing_period_start, billing_period_end,
                    due_date, usage_charges, rental_charges, tax_amount, total_amount, invoice_status
                ) VALUES (
                    :1, :2, TO_DATE(:3,'YYYY-MM-DD'), TO_DATE(:4,'YYYY-MM-DD'),
                    TO_DATE(:5,'YYYY-MM-DD'), :6, :7, :8, :9, 'UNPAID'
                )
            """, (
                new_invoice_id, customer_id,
                start_dt.strftime("%Y-%m-%d"), end_dt.strftime("%Y-%m-%d"),
                due_dt.strftime("%Y-%m-%d"),
                usage, rental, tax, total
            ))

        conn.commit()
        if new_invoice_id:
            return True, f"Subscribed to '{plan_name}'. Invoice INV-{new_invoice_id:06d} generated.", new_invoice_id
        return True, f"Subscribed to '{plan_name}'.", None
    except Exception as e:
        try:
            conn.rollback()
        except Exception:
            pass
        return False, f"Subscription failed: {str(e)}", None
    finally:
        if cursor:
            cursor.close()
        if conn:
            conn.close()

